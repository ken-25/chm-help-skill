"""CHM help file -> Markdown skill folder converter.

Standard library only. Windows only for the decompile step (uses hh.exe).

Output layout (OUT is the skill folder):
  OUT/SKILL.md      created from templates/SKILL.md.tmpl only when missing
  OUT/SOURCE.md     where the help came from (path, size, sha256, converter version)
  OUT/index.md      table of contents (from the .hhc) with links to pages
  OUT/keywords.md   keyword index (from the .hhk), only when it has entries
  OUT/pages/...     one Markdown file per help page, same relative paths as in the CHM
"""
from __future__ import annotations

import argparse
import datetime as _dt
import hashlib
import json
import posixpath
import re
import shutil
import string
import subprocess
import sys
import tempfile
import unicodedata
from html.parser import HTMLParser
from pathlib import Path

VERSION = "0.1.0"
HERE = Path(__file__).resolve().parent
GENERATED_MARK = "<!-- generated by chm-help-skill -->"
PAGE_EXT = (".htm", ".html")
IMG_EXT = (".png", ".gif", ".jpg", ".jpeg", ".bmp")

# CSS class -> Markdown. Help files often use styled <div>/<span> instead of
# <h1>/<ol>. "block" = text put at the start of the block, "after" = text
# appended after the element (e.g. a step number span -> "1. ").
DEFAULT_CLASS_MAP: dict[str, dict[str, str]] = {
    "title": {"block": "# "},
    "operation": {"block": "## "},
    "operation_group_title": {"block": "### "},
    "operation_step": {"block": ""},
    "operation_number": {"after": ". "},
    "operation_detail": {"block": "   - "},
}

SKIP_TAGS = {"script", "style", "noscript", "head", "object", "iframe"}
BLOCK_TAGS = {
    "p", "div", "pre", "blockquote", "dl", "dt", "dd", "hr", "center",
    "section", "article", "header", "footer", "form", "fieldset", "caption",
}
HEADINGS = {f"h{i}": i for i in range(1, 7)}
VOID_TAGS = {"br", "img", "hr", "meta", "link", "input", "param", "area", "base", "col"}


# --------------------------------------------------------------------------- io

_SJIS_ALIASES = {"shift_jis", "shift-jis", "x-sjis", "sjis", "ms_kanji", "windows-31j"}


def read_text(path: Path) -> str:
    """Decode an HTML-ish file using its meta charset (default cp932)."""
    data = path.read_bytes()
    if data.startswith(b"\xef\xbb\xbf"):
        return data[3:].decode("utf-8", errors="replace")
    m = re.search(rb"charset\s*=\s*[\"']?([A-Za-z0-9_\-]+)", data[:4096], re.I)
    enc = m.group(1).decode("ascii").lower() if m else "cp932"
    if enc in _SJIS_ALIASES:
        enc = "cp932"  # superset of Shift_JIS used by Windows help authoring
    try:
        return data.decode(enc, errors="replace")
    except LookupError:
        return data.decode("cp932", errors="replace")


def decompile(chm: Path, work: Path) -> Path:
    """Extract a CHM with hh.exe. The CHM is copied first because hh.exe
    silently extracts nothing when the source path contains spaces."""
    src = work / "src.chm"
    shutil.copy2(chm, src)
    raw = work / "raw"
    raw.mkdir()
    subprocess.run(["hh.exe", "-decompile", str(raw), str(src)], check=False)
    if not any(raw.rglob("*")):
        raise SystemExit(f"hh.exe extracted nothing from {chm}")
    return raw


# ---------------------------------------------------------------- .hhc / .hhk


class SitemapParser(HTMLParser):
    """Parse the HTML Help sitemap format used by .hhc (TOC) and .hhk (index).

    Produces a tree of {"name", "locals", "children"} nodes. A <UL> right after
    an entry holds that entry's children.
    """

    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.root: dict = {"name": "", "locals": [], "children": []}
        self._stack = [self.root]
        self._cur: dict | None = None
        self._last: dict | None = None

    def handle_starttag(self, tag, attrs):
        a = {k.lower(): (v or "") for k, v in attrs}
        if tag == "ul":
            self._stack.append(self._last if self._last is not None else self._stack[-1])
            self._last = None
        elif tag == "object" and a.get("type", "").lower() == "text/sitemap":
            self._cur = {"name": "", "locals": [], "children": []}
        elif tag == "param" and self._cur is not None:
            name, value = a.get("name", "").lower(), a.get("value", "")
            if name == "name" and not self._cur["name"]:
                self._cur["name"] = value.strip()
            elif name == "local" and value:
                self._cur["locals"].append(value.strip())

    def handle_endtag(self, tag):
        if tag == "object" and self._cur is not None:
            self._stack[-1]["children"].append(self._cur)
            self._last, self._cur = self._cur, None
        elif tag == "ul":
            if len(self._stack) > 1:
                self._stack.pop()
            self._last = None


def parse_sitemap(text: str) -> dict:
    p = SitemapParser()
    p.feed(text)
    p.close()
    return p.root


def norm_local(local: str) -> str:
    """'HTML\\a.html#x' / 'MS-ITS:x.chm::/a.htm' -> 'html/a.html' style key."""
    s = local.replace("\\", "/")
    if "::" in s:
        s = s.split("::", 1)[1]
    s = s.split("#", 1)[0].split("?", 1)[0].lstrip("/")
    return posixpath.normpath(s) if s else ""


# ------------------------------------------------------------- html -> markdown


class MarkdownConverter(HTMLParser):
    """Small HTML -> Markdown converter tuned for help pages."""

    def __init__(self, link_fn, image_fn, class_map=None):
        super().__init__(convert_charrefs=True)
        self.link_fn = link_fn      # href -> markdown target or None
        self.image_fn = image_fn    # src, alt -> markdown text
        self.class_map = class_map or DEFAULT_CLASS_MAP
        self.out: list[str] = []
        self.title = ""
        self._in_title = False
        self._skip = 0
        self._pre = 0
        self._lists: list[list] = []  # [kind, counter]
        self._links: list[tuple[int, str | None]] = []
        self._after: list[str | None] = []  # per open tag, appended at close
        self._open: list[str] = []
        self._table: list[list[list[str]]] | None = None
        self._table_depth = 0
        self._cell: list[str] | None = None

    # -- output helpers
    def _emit(self, s: str) -> None:
        if self._cell is not None:
            self._cell.append(s)
        else:
            self.out.append(s)

    def _buf(self) -> list[str]:
        return self._cell if self._cell is not None else self.out

    def _tail(self) -> str:
        buf = self._buf()
        for piece in reversed(buf):
            if piece:
                return piece[-1]
        return "\n"

    def _block(self, prefix: str = "") -> None:
        if self._cell is not None:
            if self._cell and self._tail() != " ":
                self._cell.append(" ")
            return
        self.out.append("\n\n" + prefix)

    # -- parser callbacks
    def handle_starttag(self, tag, attrs):
        a = {k.lower(): (v or "") for k, v in attrs}
        if tag == "title":
            self._in_title = True
            return
        if tag in SKIP_TAGS:
            if tag not in VOID_TAGS:
                self._skip += 1
            return
        if self._skip:
            return
        if tag not in VOID_TAGS:
            self._open.append(tag)
        after = None
        cls_rule = {}
        for c in a.get("class", "").split():
            cls_rule = self.class_map.get(c.lower(), cls_rule)
        if cls_rule:
            if "block" in cls_rule:
                self._block(cls_rule["block"])
            after = cls_rule.get("after")
        if tag in HEADINGS:
            self._block("#" * HEADINGS[tag] + " ")
        elif tag in BLOCK_TAGS and "block" not in cls_rule:
            self._block()
            if tag == "hr":
                self._emit("---")
            elif tag == "pre":
                self._pre += 1
                self._emit("```\n")
        elif tag in ("ul", "ol", "menu"):
            self._lists.append([tag, 0])
            self._block()
        elif tag == "li":
            depth = max(len(self._lists), 1)
            kind = self._lists[-1] if self._lists else ["ul", 0]
            kind[1] += 1
            marker = f"{kind[1]}. " if kind[0] == "ol" else "- "
            if self._cell is not None:
                self._emit(" ・")
            else:
                self.out.append("\n" + "  " * (depth - 1) + marker)
        elif tag == "br":
            self._emit(" " if self._cell is not None else "\n")
        elif tag in ("b", "strong"):
            self._emit("**")
            after = "**" + (after or "")
        elif tag == "img":
            self._emit(self.image_fn(a.get("src", ""), a.get("alt", "")))
        elif tag == "a" and "href" in a:
            self._links.append((len(self._buf()), self.link_fn(a["href"])))
        elif tag == "table":
            self._table_depth += 1
            if self._table_depth == 1:
                self._block()
                self._table = []
        elif tag == "tr" and self._table_depth == 1 and self._table is not None:
            self._table.append([])
        elif tag in ("td", "th") and self._table_depth == 1 and self._table is not None:
            if not self._table:
                self._table.append([])
            self._cell = []
        if tag not in VOID_TAGS:
            self._after.append(after)
        elif after:
            self._emit(after)

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False
            return
        if tag in SKIP_TAGS:
            if self._skip:
                self._skip -= 1
            return
        if self._skip or tag in VOID_TAGS:
            return
        if tag not in self._open:
            return  # stray close tag
        # close everything opened after this tag (unclosed <p>, <li> ...)
        while self._open:
            t = self._open.pop()
            after = self._after.pop()
            self._close(t, after)
            if t == tag:
                break

    def _close(self, tag, after):
        if tag == "a" and self._links:
            start, target = self._links.pop()
            buf = self._buf()
            text = "".join(buf[start:]).strip()
            if target and text:
                del buf[start:]
                buf.append(f"[{text}]({target})")
        if after:
            self._emit(after)
        if tag in ("td", "th") and self._cell is not None and self._table is not None:
            cell = re.sub(r"\s+", " ", "".join(self._cell)).strip().replace("|", "\\|")
            self._table[-1].append(cell)
            self._cell = None
        elif tag == "table":
            self._table_depth -= 1
            if self._table_depth == 0 and self._table is not None:
                self._flush_table()
        elif tag in ("ul", "ol", "menu") and self._lists:
            self._lists.pop()
            self._block()
        elif tag == "pre" and self._pre:
            self._pre -= 1
            self._emit("\n```")
            self._block()
        elif tag in HEADINGS or tag in BLOCK_TAGS:
            self._block()

    def _flush_table(self):
        rows = [r for r in self._table if any(c for c in r)]
        self._table = None
        if not rows:
            return
        width = max(len(r) for r in rows)
        if width == 1:  # layout table: just paragraphs
            self.out.append("\n\n" + "\n\n".join(r[0] for r in rows) + "\n\n")
            return
        rows = [r + [""] * (width - len(r)) for r in rows]
        lines = ["| " + " | ".join(rows[0]) + " |", "|" + "---|" * width]
        lines += ["| " + " | ".join(r) + " |" for r in rows[1:]]
        self.out.append("\n\n" + "\n".join(lines) + "\n\n")

    def handle_data(self, data):
        if self._in_title:
            self.title += data
            return
        if self._skip:
            return
        data = data.replace("\xa0", " ")
        if self._pre:
            self._emit(data)
            return
        data = re.sub(r"[ \t\r\n\f]+", " ", data)
        if self._tail() in "\n " or self._tail() == "":
            data = data.lstrip()
        if data:
            self._emit(data)

    def markdown(self) -> str:
        text = "".join(self.out)
        lines = [ln.rstrip() for ln in text.split("\n")]
        text = "\n".join(lines)
        text = re.sub(r"\n{3,}", "\n\n", text).strip()
        # drop headings / list markers left with no text
        text = re.sub(r"(?m)^[ \t]*(#{1,6}|-|\d+\.)[ \t]*$\n?", "", text)
        text = re.sub(r"\*\*\s*\*\*", "", text)
        return re.sub(r"\n{3,}", "\n\n", text).strip() + "\n"


# ------------------------------------------------------------------ conversion


def relpath_posix(target: str, start_dir: str) -> str:
    return posixpath.relpath(target, start_dir or ".")


def md_name(rel: str) -> str:
    root, _ = posixpath.splitext(rel)
    return root + ".md"


def _same(a: str, b: str) -> bool:
    """Title equality ignoring full/half width and spacing (ＣＧ == CG)."""
    def n(s):
        return re.sub(r"\s+", "", unicodedata.normalize("NFKC", s))
    return n(a) == n(b)


def build(chm: Path, out: Path, name: str, title: str, with_images: bool,
          class_map: dict, keep_work: bool = False) -> dict:
    out = out.resolve()
    if out.exists() and any(out.iterdir()) and not (out / "SOURCE.md").exists():
        if not (out / "SKILL.md").exists():
            raise SystemExit(f"{out} is not empty and was not created by this tool")
    work = Path(tempfile.mkdtemp(prefix="chm2md-"))
    try:
        raw = decompile(chm, work)
        return _build_from_raw(chm, raw, out, name, title, with_images, class_map)
    finally:
        if not keep_work:
            shutil.rmtree(work, ignore_errors=True)


def _index_files(raw: Path) -> tuple[dict[str, Path], dict[str, Path]]:
    pages, images = {}, {}
    for p in raw.rglob("*"):
        if not p.is_file():
            continue
        rel = p.relative_to(raw).as_posix()
        key = rel.lower()
        if p.suffix.lower() in PAGE_EXT:
            pages[key] = p
        elif p.suffix.lower() in IMG_EXT:
            images[key] = p
    return pages, images


def _build_from_raw(chm, raw, out, name, title, with_images, class_map) -> dict:
    pages, images = _index_files(raw)
    hhc = next(iter(sorted(raw.rglob("*.hhc"))), None)
    hhk = next(iter(sorted(raw.rglob("*.hhk"))), None)
    toc = parse_sitemap(read_text(hhc)) if hhc else {"children": []}
    kw = parse_sitemap(read_text(hhk)) if hhk else {"children": []}
    # .hhc paths are relative to the .hhc location
    hhc_dir = hhc.parent.relative_to(raw).as_posix() if hhc else ""
    hhk_dir = hhk.parent.relative_to(raw).as_posix() if hhk else ""

    def resolve(local: str, base_dir: str) -> str | None:
        key = norm_local(local)
        if not key:
            return None
        for cand in (posixpath.normpath(posixpath.join(base_dir, key)), key):
            if cand.lower() in pages:
                return pages[cand.lower()].relative_to(raw).as_posix()
        return None

    # breadcrumbs: page -> first TOC path that reaches it
    crumbs: dict[str, list[str]] = {}

    def walk(node, trail):
        for ch in node["children"]:
            path = trail + [ch["name"]]
            for loc in ch["locals"]:
                rel = resolve(loc, hhc_dir)
                if rel:
                    crumbs.setdefault(rel, path)
            walk(ch, path)

    walk(toc, [])

    pages_dir = out / "pages"
    if pages_dir.exists():
        shutil.rmtree(pages_dir)
    pages_dir.mkdir(parents=True)

    titles: dict[str, str] = {}
    copied_images = 0
    for key in sorted(pages):
        src = pages[key]
        rel = src.relative_to(raw).as_posix()
        page_dir = posixpath.dirname(rel)
        out_md = md_name(rel)

        def link_fn(href, _dir=page_dir, _out=out_md):
            h = href.strip()
            if re.match(r"(?i)^(https?|mailto):", h):
                return h
            if re.match(r"(?i)^(javascript|ms-its|mk:@msitstore|its):", h) or "::" in h:
                return None
            target = h.split("#", 1)[0]
            if not target:
                return None
            joined = posixpath.normpath(posixpath.join(_dir, target.replace("\\", "/")))
            hit = pages.get(joined.lower())
            if not hit:
                return None
            return relpath_posix(md_name(hit.relative_to(raw).as_posix()),
                                 posixpath.dirname(_out))

        def image_fn(srcattr, alt, _dir=page_dir):
            nonlocal copied_images
            s = srcattr.strip().replace("\\", "/")
            fname = posixpath.basename(s) or "?"
            label = alt.strip() or fname
            if not with_images:
                return f"[図: {label}]"
            joined = posixpath.normpath(posixpath.join(_dir, s))
            img = images.get(joined.lower())
            if not img:
                return f"[図: {label}]"
            dst = pages_dir / img.relative_to(raw)
            if not dst.exists():
                dst.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(img, dst)
                copied_images += 1
            return f"![{label}]({relpath_posix(img.relative_to(raw).as_posix(), _dir)})"

        conv = MarkdownConverter(link_fn, image_fn, class_map)
        conv.feed(read_text(src))
        conv.close()
        body = conv.markdown()
        page_title = re.sub(r"\s+", " ", conv.title.replace("\xa0", " ")).strip()
        if not page_title:
            m = re.search(r"(?m)^#{1,6} (.+)$", body)
            page_title = m.group(1).strip() if m else posixpath.basename(rel)
        # the page usually repeats its title as the first heading
        first = body.split("\n", 1)
        if first and _same(re.sub(r"^#+\s*", "", first[0]), page_title):
            body = first[1].lstrip("\n") if len(first) > 1 else ""
        titles[rel] = page_title
        head = [f"# {page_title}", ""]
        if rel in crumbs:
            head.append("> 場所: " + " > ".join(crumbs[rel]))
        head.append(f"> 元ファイル: {rel}")
        dst = pages_dir / out_md
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text("\n".join(head) + "\n\n" + body, encoding="utf-8", newline="\n")

    # index.md
    lines = [GENERATED_MARK, f"# {title} ヘルプ 目次", ""]

    def toc_lines(node, depth):
        for ch in node["children"]:
            rel = next((r for r in (resolve(l, hhc_dir) for l in ch["locals"]) if r), None)
            label = ch["name"] or (titles.get(rel) if rel else "") or "(無題)"
            item = f"[{label}](pages/{md_name(rel)})" if rel else label
            lines.append("  " * depth + "- " + item)
            toc_lines(ch, depth + 1)

    toc_lines(toc, 0)
    orphans = sorted(r for r in titles if r not in crumbs)
    if orphans:
        lines += ["", "## 目次にないページ", ""]
        lines += [f"- [{titles[r]}](pages/{md_name(r)})" for r in orphans]
    (out / "index.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")

    # keywords.md
    kw_lines: list[str] = []

    def kw_walk(node, trail):
        for ch in node["children"]:
            words = trail + [ch["name"]]
            targets = [r for r in (resolve(l, hhk_dir) for l in ch["locals"]) if r]
            if targets:
                links = ", ".join(f"[{titles.get(r, r)}](pages/{md_name(r)})" for r in targets)
                kw_lines.append(f"- {' / '.join(words)}: {links}")
            kw_walk(ch, words)

    kw_walk(kw, [])
    kw_path = out / "keywords.md"
    if kw_lines:
        kw_path.write_text("\n".join([GENERATED_MARK, f"# {title} ヘルプ 索引", ""] + kw_lines)
                           + "\n", encoding="utf-8", newline="\n")
    elif kw_path.exists():
        kw_path.unlink()

    stats = {
        "pages": len(titles), "toc_pages": len(crumbs), "orphans": len(orphans),
        "keywords": len(kw_lines), "images_copied": copied_images,
    }
    _write_source(chm, out, stats)
    _write_skill(out, name, title, chm, stats, bool(kw_lines))
    return stats


def _converter_commit() -> str:
    try:
        r = subprocess.run(["git", "-C", str(HERE), "rev-parse", "--short", "HEAD"],
                           capture_output=True, text=True, timeout=10)
        return r.stdout.strip() or "uncommitted"
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def _write_source(chm: Path, out: Path, stats: dict) -> None:
    st = chm.stat()
    sha = hashlib.sha256(chm.read_bytes()).hexdigest()
    mtime = _dt.datetime.fromtimestamp(st.st_mtime).strftime("%Y-%m-%d %H:%M")
    lines = [
        GENERATED_MARK, "# 出典", "",
        f"- 元ファイル: `{chm}`",
        f"- サイズ: {st.st_size:,} bytes / 更新日時: {mtime}",
        f"- SHA-256: `{sha}`",
        f"- 変換: chm-help-skill {VERSION} ({_converter_commit()})",
        f"- 変換日: {_dt.date.today().isoformat()}",
        f"- ページ数: {stats['pages']}(目次に載るもの {stats['toc_pages']})"
        f" / 索引語: {stats['keywords']} / 画像: {stats['images_copied']}",
    ]
    (out / "SOURCE.md").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def _write_skill(out: Path, name: str, title: str, chm: Path, stats: dict, has_kw: bool) -> None:
    dst = out / "SKILL.md"
    if dst.exists():
        return  # hand edits to the skill text are kept
    tmpl = string.Template((HERE / "templates" / "SKILL.md.tmpl").read_text(encoding="utf-8"))
    kw_step = "また keywords.md(索引語)も検索する。" if has_kw else ""
    dst.write_text(tmpl.substitute(name=name, title=title, chm_name=chm.name,
                                   pages=stats["pages"], keywords_step=kw_step),
                   encoding="utf-8", newline="\n")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Convert a CHM help file into a Markdown skill folder")
    ap.add_argument("--chm", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path, help="skill folder to write")
    ap.add_argument("--name", required=True, help="skill name, e.g. example-help")
    ap.add_argument("--title", required=True, help="software name used in SKILL.md")
    ap.add_argument("--with-images", action="store_true", help="copy images referenced by pages")
    ap.add_argument("--class-map", type=Path, help="JSON file merged over the CSS class map")
    ap.add_argument("--keep-work", action="store_true", help="keep the decompiled files")
    args = ap.parse_args(argv)
    if not args.chm.is_file():
        ap.error(f"not found: {args.chm}")
    cmap = dict(DEFAULT_CLASS_MAP)
    if args.class_map:
        cmap.update(json.loads(args.class_map.read_text(encoding="utf-8")))
    args.out.mkdir(parents=True, exist_ok=True)
    stats = build(args.chm, args.out, args.name, args.title, args.with_images, cmap, args.keep_work)
    sys.stdout.reconfigure(encoding="utf-8")
    print(json.dumps({"out": str(args.out.resolve()), **stats}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
